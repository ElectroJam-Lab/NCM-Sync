const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { Database } = require('../../src/backend/database.cjs');
const { FileStore } = require('../../src/backend/file-store.cjs');
const { AppService } = require('../../src/backend/app-service.cjs');
const { NeteaseClient } = require('../../src/backend/netease.cjs');
const { TaskManager } = require('../../src/backend/task-manager.cjs');
const { wavFixture, assertMp3Bitrate } = require('../audio-fixture.cjs');

test('码率设置持久化、拒绝非法值，并只转码本次选择的新歌曲，任务内码率保持一致', async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ncmsync-mp3-sync-'));
  const fileStore = new FileStore(root);
  const db = await new Database(path.join(fileStore.dataPath, 'test.sqlite')).init();
  const netease = new NeteaseClient({ mock: true }); const tasks = new TaskManager();
  const service = new AppService({ db, fileStore, netease, tasks, rootPath: root });
  t.after(async () => { service.stop(); if (tasks.active) await service.cancelTask(false);
    assert.ok(path.basename(root).startsWith('ncmsync-mp3-sync-')); fs.rmSync(root, { recursive: true, force: true }); });
  assert.equal(db.getSettings().mp3Bitrate, 0);
  await service.setupUser('123456789'); service.setSyncSelection(['1001']);
  const folder = path.join(root, 'custom'); fs.mkdirSync(folder);
  const original = path.join(folder, 'Test Artist - Neon Run.mp3'); fs.writeFileSync(original, 'untouched');
  const item = await service.mapPlaylist('1001', folder);
  await service.saveTrackChoices(item.id, item.revision, [{ id: '501', action: 'keep', enabled: false }]);
  service.updateSettings({ mp3Bitrate: 128 });
  for (const invalid of ['192', 127, -1, 100000, null, true]) assert.throws(() => service.updateSettings({ mp3Bitrate: invalid }), /MP3 码率/);
  assert.equal((await new Database(db.filePath).init()).getSettings().mp3Bitrate, 128);
  let audioCalls = 0;
  netease.getAudioResponse = async () => { audioCalls++; service.updateSettings({ mp3Bitrate: 192 }); return new Response(wavFixture()); };
  service.startSync(); await service.syncPromise;
  assert.equal(tasks.getState().error, ''); assert.equal(audioCalls, 1);
  const song = db.get('SELECT * FROM songs WHERE track_id=?', ['502']);
  assert.equal(song.extension, 'mp3');
  assertMp3Bitrate(fs.readFileSync(song.entity_path), 128);
  assert.ok(fs.statSync(song.entity_path).nlink >= 2);
  assert.equal(fs.readFileSync(original, 'utf8'), 'untouched');
  const encoded = fs.readFileSync(song.entity_path);
  service.updateSettings({ mp3Bitrate: 320 });
  service.startSync(); await service.syncPromise;
  assert.equal(audioCalls, 1); assert.deepEqual(fs.readFileSync(song.entity_path), encoded);
  assert.equal(fs.readFileSync(original, 'utf8'), 'untouched');
});
